function iconSize(el) {
    const px = parseFloat(getComputedStyle(el).fontSize);
    return Number.isFinite(px) && px > 0 ? Math.round(px) : 20;
}

/** Ubah semua placeholder `span.cc-icon` di dalam `root` jadi SVG Lucide. */
export function convertIcons(root = document) {
    const nodes = root.querySelectorAll("span.cc-icon:not([data-cc-done])");
    if (!nodes.length) return 0;

    const batch = [];
    nodes.forEach((el) => {
        el.setAttribute("data-cc-done", "1");
        const name = MATERIAL_TO_LUCIDE[el.textContent.trim()] || "circle-help";
        const size = iconSize(el);
        const tmp = document.createElement("span");
        tmp.setAttribute("data-lucide", name);
        tmp.setAttribute("style", `width:${size}px;height:${size}px;`);
        // Pindahkan seluruh class utilitas (warna dsb) ke placeholder baru.
        const cls = el
            .getAttribute("class")
            .replace(/\bcc-icon\b/g, "")
            .trim();
        if (cls) tmp.setAttribute("class", cls);
        batch.push([el, tmp]);
    });
    batch.forEach(([el, tmp]) => el.replaceWith(tmp));

    // Satu pemanggilan untuk seluruh batch (createIcons memindahkan
    // atribut class & style placeholder ke SVG hasil konversi).
    createIcons({ icons: ICONS, attrs: { "stroke-width": 2 }, root });
    return batch.length;
}

let observerStarted = false;

export function initIcons() {
    convertIcons(document);
    document.documentElement.classList.remove("cc-icons-pending");
    window.__ccIconsDone = true;

    if (observerStarted) return;
    observerStarted = true;

    const obs = new MutationObserver((mutations) => {
        // Konversi hanya pada subtree yang baru di-inject (hemat, dan
        // ikon lama yang sudah jadi SVG tidak diproses ulang).
        const roots = new Set();
        for (const m of mutations) {
            if (m.type !== "childList") continue;
            for (const n of m.addedNodes) {
                if (n.nodeType !== 1) continue;
                if (
                    (n.matches && n.matches("span.cc-icon")) ||
                    (n.querySelector && n.querySelector("span.cc-icon"))
                ) {
                    roots.add(n.parentElement || document.body);
                }
            }
        }
        roots.forEach((rootEl) => convertIcons(rootEl));
    });
    obs.observe(document.body, { childList: true, subtree: true });
}
